// Regenerates src/seasonal-prior.ts from the classifier's weekly (quarter-month) species prior.
// Run after classifier/species/atlanta-weekly.json changes (classifier/build/seasonal.py).
//
//   node scripts/gen-seasonal-prior.mjs
//
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const inPath = join(here, '..', '..', 'classifier', 'species', 'atlanta-weekly.json');
const outPath = join(here, '..', 'src', 'seasonal-prior.ts');

const prior = JSON.parse(readFileSync(inPath, 'utf8'));
if (prior.version !== 1) throw new Error(`unsupported prior version ${prior.version}`);

const lines = [];
for (const name of Object.keys(prior.species).sort()) {
    const s = prior.species[name];
    if (s.commonness.length !== 48) throw new Error(`${name}: expected 48 quarter-months`);
    // Whole percent is plenty: the plugin only compares against a ~0.15 floor.
    const c = s.commonness.map(x => Math.round(x * 100));
    lines.push(`    ${JSON.stringify(name.toLowerCase())}: { obs: ${s.obs}, ${s.always ? 'always: true, ' : ''}pct: [${c.join(',')}] },`);
}

const out = `// Generated by scripts/gen-seasonal-prior.mjs from classifier/species/atlanta-weekly.json --
// do not hand-edit. Re-run that script after classifier/build/seasonal.py rebuilds the prior.
// How common each species is around Atlanta in each of the year's 48 quarter-months
// (index = (month-1)*4 + min((day-1)/7, 3)): pct is a 0-100 rank among the species seen that
// quarter-month, obs the sightings behind it. Source: ${prior.source}; generated ${prior.generated}.
export interface SeasonalEntry {
    obs: number;
    always?: true;
    pct: readonly number[];
}

export const SEASONAL_PRIOR: Readonly<Record<string, SeasonalEntry>> = {
${lines.join('\n')}
};
`;
writeFileSync(outPath, out, 'utf8');
console.log(`Wrote ${lines.length} species to ${outPath}`);
