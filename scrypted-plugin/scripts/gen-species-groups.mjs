// Regenerates src/species-groups.ts from the classifier's local species list.
// Run after classifier/species/atlanta.json changes (new local species, region change, etc).
//
//   node scripts/gen-species-groups.mjs
//
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const speciesPath = join(here, '..', '..', 'classifier', 'species', 'atlanta.json');
const outPath = join(here, '..', 'src', 'species-groups.ts');

const species = JSON.parse(readFileSync(speciesPath, 'utf8'));
const map = {};
for (const s of species) {
    const key = s.label.toLowerCase();
    const grp = s.group === 'Birds' ? 'bird' : s.group === 'Mammals' ? 'mammal' : null;
    if (!grp) throw new Error(`unexpected classifier group "${s.group}" for ${s.label}`);
    if (map[key] && map[key] !== grp) throw new Error(`conflicting group for duplicate label "${key}"`);
    map[key] = grp;
}

const entries = Object.entries(map).sort(([a], [b]) => a.localeCompare(b));
const lines = entries.map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const out = `// Generated by scripts/gen-species-groups.mjs from classifier/species/atlanta.json --
// do not hand-edit. Re-run that script after the classifier's local species list changes.
// Maps a species label, lowercased, to the taxonomic group the local Atlanta-area
// classifier (device 248) assigns it -- birds vs. mammals -- so visit grouping
// matches the model's own taxonomy instead of a hand-maintained keyword guess.
import type { VisitGroup } from './store';

export const SPECIES_GROUPS: Readonly<Record<string, VisitGroup>> = {
${lines.join('\n')}
};
`;
writeFileSync(outPath, out, 'utf8');
console.log(`Wrote ${entries.length} species -> group mappings to ${outPath}`);
