// Regenerates src/taxonomy.ts from the classifier's iNat21 category table.
// Run after classifier/data/inat21_categories.json changes.
//
//   node scripts/gen-taxonomy.mjs
//
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const inatPath = join(here, '..', '..', 'classifier', 'data', 'inat21_categories.json');
const outPath = join(here, '..', 'src', 'taxonomy.ts');

// Only classes BirdNET-Go's multi-taxa Perch v2 model can plausibly emit as a non-bird
// detection: mammals, amphibians, reptiles, insects. Aves is deliberately excluded --
// grouping defaults to 'bird' for anything not found here, since Perch is mostly birds,
// so storing ~1,500 redundant Aves entries would only bloat the bundle for no benefit.
// Plants/fungi/fish/mollusks/etc (the other ~5,000 iNat21 classes) are irrelevant to an
// audio classifier and are skipped entirely.
const RELEVANT_CLASSES = ['Mammalia', 'Amphibia', 'Reptilia', 'Insecta'];
const relevantSet = new Set(RELEVANT_CLASSES);

const rows = JSON.parse(readFileSync(inatPath, 'utf8'));
const speciesByClass = { Mammalia: [], Amphibia: [], Reptilia: [], Insecta: [] };
const genusByClass = { Mammalia: [], Amphibia: [], Reptilia: [], Insecta: [] };
const seenGenus = new Set();
let kept = 0;
for (const row of rows) {
    if (!relevantSet.has(row.class)) continue;
    kept++;
    const name = String(row.name).toLowerCase().trim();
    const genus = String(row.genus).toLowerCase().trim();
    speciesByClass[row.class].push(name);
    if (!seenGenus.has(genus)) {
        seenGenus.add(genus);
        genusByClass[row.class].push(genus);
    }
}
for (const cls of RELEVANT_CLASSES) { speciesByClass[cls].sort(); genusByClass[cls].sort(); }

const fmtGroup = groups => RELEVANT_CLASSES
    .map(cls => `    ${cls}: [\n${groups[cls].map(n => `        ${JSON.stringify(n)},`).join('\n')}\n    ],`)
    .join('\n');
const genusCount = RELEVANT_CLASSES.reduce((n, cls) => n + genusByClass[cls].length, 0);

const out = `// Generated by scripts/gen-taxonomy.mjs from classifier/data/inat21_categories.json --
// do not hand-edit. Re-run that script after the iNat21 category table changes.
// Scientific-name and genus lookups for BirdNET-Go's multi-taxa Perch v2 output: maps a
// binomial (lowercased "genus species") or bare genus to its taxonomic Class, for every
// non-Aves class Perch can plausibly emit (mammals, amphibians, reptiles, insects). Species
// not found here default to Aves (bird) -- Perch's output is overwhelmingly birds, and the
// other ~5,000 iNat21 classes (plants, fungi, fish, mollusks, ...) can never be a real
// bioacoustic detection, so they are excluded from the bundle entirely. Grouped by class
// (rather than one map entry per name) so the class name isn't repeated thousands of times.
export type TaxonomicClass = 'Mammalia' | 'Amphibia' | 'Reptilia' | 'Insecta';

const SPECIES_BY_CLASS: Readonly<Record<TaxonomicClass, readonly string[]>> = {
${fmtGroup(speciesByClass)}
};

const GENUS_BY_CLASS: Readonly<Record<TaxonomicClass, readonly string[]>> = {
${fmtGroup(genusByClass)}
};

function invert(groups: Readonly<Record<TaxonomicClass, readonly string[]>>): ReadonlyMap<string, TaxonomicClass> {
    const map = new Map<string, TaxonomicClass>();
    for (const cls of Object.keys(groups) as TaxonomicClass[])
        for (const name of groups[cls]) map.set(name, cls);
    return map;
}

export const SPECIES_CLASS: ReadonlyMap<string, TaxonomicClass> = invert(SPECIES_BY_CLASS);
export const GENUS_CLASS: ReadonlyMap<string, TaxonomicClass> = invert(GENUS_BY_CLASS);
`;
writeFileSync(outPath, out, 'utf8');
console.log(`Kept ${kept}/${rows.length} rows -> ${kept} species + ${genusCount} genera -> ${outPath} (${out.length} bytes)`);
